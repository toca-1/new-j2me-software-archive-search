#!/usr/bin/env python3
"""Generate compact static indexes from j2me-search-index-with-parts.csv.

No third-party packages needed. Run this from a clone of the GitHub Pages repo:
    python3 build_site.py --input ~/Downloads/j2me-search-index-with-parts.csv

Records sorted by filename are sharded for fast result retrieval. Filename searches
load a separate compressed *names-only* catalog once (not the 78MB CSV). Exact
SHA-1 searches load a single small hash-prefix index and a records shard.
"""
from __future__ import annotations
import argparse
import csv
import gzip
import json
import re
from collections import defaultdict
from pathlib import Path
import shutil

REQ = ('filename','archive_path','size_bytes','sha1','solid_block','compressed_data_parts','required_parts')
SHA1 = re.compile(r'^[0-9a-fA-F]{40}$')
PART = re.compile(r'^\d{3}$')
CHUNK_SIZE = 1024
NAME_CHUNK_SIZE = 32768


def write_json(path: Path, value):
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open('w', encoding='utf-8') as fp:
        json.dump(value, fp, ensure_ascii=False, separators=(',',':'))


def parse_parts(value: str, number: int, field: str):
    p = value.split(',')
    if not p or any(not PART.fullmatch(x) or int(x) < 1 or int(x) > 43 for x in p):
        raise ValueError(f'Row {number}: invalid {field} = {value!r}')
    nums = [int(x) for x in p]
    if sorted(set(nums)) != nums:
        raise ValueError(f'Row {number}: {field} should list ordered unique parts')
    return nums


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--input', type=Path, required=True, help='The 7-column CSV generated by j2me_add_archive_parts.py')
    parser.add_argument('--out', type=Path, default=Path(__file__).resolve().parent, help='Directory containing index.html')
    parser.add_argument('--expected-count', type=int, help='Fail unless exactly this many nonempty file rows are present')
    args = parser.parse_args()
    src = args.input.expanduser().resolve()
    output = args.out.expanduser().resolve()
    if not src.is_file():
        parser.error('CSV not found: ' + str(src))
    if not (output / 'index.html').is_file():
        parser.error('Output directory must contain index.html: ' + str(output))
    records = []
    sha_seen = set()
    paths_seen = set()
    block_parts = {}
    with src.open('r', encoding='utf-8-sig', newline='') as fp:
        rd = csv.DictReader(fp)
        missing = set(REQ) - set(rd.fieldnames or [])
        if missing:
            parser.error('Missing CSV columns: '+ ', '.join(sorted(missing)))
        for number, row in enumerate(rd,2):
            sha = row['sha1'].lower()
            if not SHA1.fullmatch(sha):
                raise ValueError(f'Row {number}: invalid sha1')
            path = row['archive_path']
            name = row['filename']
            size = int(row['size_bytes'])
            block = int(row['solid_block'])
            if not name or not path or size <= 0 or block not in range(63):
                raise ValueError(f'Row {number}: invalid filename, path, size, or solid_block')
            # This archive's nonempty original files have unique SHA-1 values.
            if sha in sha_seen or path in paths_seen:
                raise ValueError(f'Row {number}: repeated sha1 or archive_path')
            sha_seen.add(sha)
            paths_seen.add(path)
            parts = parse_parts(row['required_parts'],number,'required_parts')
            data_parts = parse_parts(row['compressed_data_parts'],number,'compressed_data_parts')
            if 1 not in parts or 43 not in parts or sorted(set(data_parts) | {1,43}) != parts:
                raise ValueError(f'Row {number}: required parts mismatch')
            if block in block_parts and block_parts[block] != parts:
                raise ValueError(f'Row {number}: inconsistent required parts for block {block}')
            block_parts[block] = parts
            records.append([name,path,size,sha,block,','.join(f'{x:03d}' for x in parts)])
            if len(records)%100_000 == 0:
                print(f'Validated {len(records):,} rows...', flush=True)
    if args.expected_count is not None and len(records) != args.expected_count:
        raise ValueError(f'Expected {args.expected_count:,} entries, got {len(records):,}')
    if not records:
        raise ValueError('CSV contains no entries')
    records.sort(key=lambda row: (row[0].casefold(),row[1].casefold()))
    datadir = output / 'data'
    # Avoid stale shards remaining after a rebuild with a different dataset.
    if datadir.exists():
        shutil.rmtree(datadir)
    for i in range(0, len(records), CHUNK_SIZE):
        write_json(datadir / 'records' / f'{i//CHUNK_SIZE:04d}.json', records[i:i+CHUNK_SIZE])
    print(f'Wrote {(len(records)+CHUNK_SIZE-1)//CHUNK_SIZE:,} record shards.',flush=True)
    for start in range(0, len(records), NAME_CHUNK_SIZE):
        names = [r[0].lower() for r in records[start:start+NAME_CHUNK_SIZE]]
        payload = json.dumps(names,ensure_ascii=False,separators=(',',':')).encode('utf-8')
        target = datadir / 'names' / f'{start//NAME_CHUNK_SIZE:03d}.bin'
        target.parent.mkdir(parents=True,exist_ok=True)
        with target.open('wb') as fp:
            fp.write(gzip.compress(payload, compresslevel=9, mtime=0))
    print(f'Wrote {(len(records)+NAME_CHUNK_SIZE-1)//NAME_CHUNK_SIZE:,} compressed filename shards.',flush=True)
    hashes = defaultdict(dict)
    for identifier, row in enumerate(records):
        hashes[row[3][:2]][row[3]] = identifier
    for prefix in (f'{n:02x}' for n in range(256)):
        write_json(datadir / 'hashes' / f'{prefix}.json', hashes[prefix])
    write_json(datadir / 'manifest.json', {
        'archive':'j2me-archive-unified-2019-09',
        'records':len(records),
        'blocks':63,
        'representative_blocks_tested':63,
        'record_chunk_size':CHUNK_SIZE,
        'name_chunk_size':NAME_CHUNK_SIZE,
        'name_chunks':(len(records)+NAME_CHUNK_SIZE-1)//NAME_CHUNK_SIZE,
        'search_limit':40,
        'schema':['filename','archive_path','size_bytes','sha1','solid_block','required_parts']
    })
    total = sum(f.stat().st_size for f in datadir.rglob('*') if f.is_file())
    print(f'Complete: {len(records):,} files, {len(block_parts)} blocks, {total/1048576:.1f} MiB static website data.')
    print(f'Publish {output} to the repository. No large CSV is required in the GitHub Pages site.')

if __name__ == '__main__':
    main()
